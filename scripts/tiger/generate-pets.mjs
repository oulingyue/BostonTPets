// Writes tiger/seeds/pets.sql from the game catalog, so Tiger knows each pet's rarity, line and
// roll weight. The drop-rate check compares real pulls against these weights.
// Run with `npm run tiger:pets` after changing catalog.ts.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { CATALOG, TIER_WEIGHT } from '../../supabase/functions/_shared/game/catalog.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'tiger', 'seeds', 'pets.sql');

const quote = (value) => (value === null ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`);

const rows = Object.values(CATALOG)
  .sort((a, b) => a.petId.localeCompare(b.petId))
  .map((pet) => `  (${[pet.petId, pet.name, pet.rarity, pet.line].map(quote).join(', ')}, ${TIER_WEIGHT[pet.rarity]})`);

const sql = `-- Generated by scripts/tiger/generate-pets.mjs from catalog.ts. Do not edit by hand.
-- weight is the pet's weight on its line's roll table; every line's table sums to 100.
-- Shared commons (line NULL) are on every line's table.
INSERT INTO pets (pet_id, name, rarity, line, weight) VALUES
${rows.join(',\n')}
ON CONFLICT (pet_id) DO UPDATE
SET name = EXCLUDED.name, rarity = EXCLUDED.rarity, line = EXCLUDED.line, weight = EXCLUDED.weight;
`;

writeFileSync(OUT, sql);
console.log(`Wrote ${Object.keys(CATALOG).length} pets to ${path.relative(ROOT, OUT)}`);
